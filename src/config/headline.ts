/*
  Presentation fields derived from validated report data, shared by the web
  report and the PDF. Nothing here is generated by the model: the overall
  score, bands, confidence, the strongest supported opportunity and the next
  action are all computed from fields that already exist in the report.
  Server-safe: relative imports only.
*/
import { assessmentCoverage, CRITERIA, criterion, groupScore, overallBand, overallScore, readinessFraming, scoreTone, scoreWord, sourceConfidence, type CriterionGroup, type CriterionId, type OverallScore, type ScoreBasis, type Tone } from './scoring';

/* Structural types: the browser's report types and the server's Zod output both satisfy them. */
export interface ScorecardItem { id: CriterionId; score: number | null; basis: ScoreBasis; note: string; improvement: string }
export interface Source { index: number; title: string; url: string; publisher: string | null; published_date: string | null; geography: string | null; unit: string | null; period: string | null; claim_type: 'historical' | 'forecast' | 'other'; used_for: string }
export interface Chart { kind: 'evidence' | 'scenario' | 'none'; title: string; unit: string; series: { label: string; value: number; source_index: number | null }[]; note: string }
export interface ReportLike {
  scorecard: ScorecardItem[];
  swot: { strengths: string[]; weaknesses: string[]; opportunities: string[]; threats: string[] };
  claims: { kind: string; source_indexes: number[] }[];
  sources: Source[];
  experiment: { description: string };
  improvements: { action: string }[];
}
type StandardReport = ReportLike;

export interface Headline {
  overall: OverallScore;
  band: { title: string; tone: Tone };
  /** Quality of the sources themselves. */
  sources: ReturnType<typeof sourceConfidence>;
  /** How much of the assessment is evidence-backed, assumed or unknown. */
  coverage: ReturnType<typeof assessmentCoverage>;
  /** Encouraging, honest next-step framing for the current formulation. */
  framing: ReturnType<typeof readinessFraming>;
  /** The best-supported positive: the top evidence-based criterion, else the first listed opportunity. */
  strongest: { text: string; kind: 'criterion' | 'opportunity' | 'none' };
  /** The most useful next action: the experiment, else the first recommendation. */
  nextAction: string;
  groups: Record<CriterionGroup, { score: number | null; scored: number; total: number }>;
}

export function deriveHeadline(report: StandardReport): Headline {
  const items = report.scorecard.map((s) => ({ id: s.id, score: s.score, basis: s.basis }));
  const overall = overallScore(items);
  const sources = sourceConfidence(report.sources);
  const coverage = assessmentCoverage(items);
  const topEvidence = [...report.scorecard]
    .filter((s) => s.basis === 'evidence' && s.score !== null && s.score >= 60)
    .sort((a, b) => (b.score ?? 0) - (a.score ?? 0))[0];
  const strongest = topEvidence
    ? { text: `${criterion(topEvidence.id)?.label ?? topEvidence.id} (${topEvidence.score}/100): ${topEvidence.note}`, kind: 'criterion' as const }
    : report.swot.opportunities[0]
      ? { text: report.swot.opportunities[0], kind: 'opportunity' as const }
      : report.swot.strengths[0]
        ? { text: report.swot.strengths[0], kind: 'opportunity' as const }
        : { text: 'No supported opportunity could be identified from the available evidence.', kind: 'none' as const };
  const nextAction = report.experiment.description || report.improvements[0]?.action || 'Talk to ten potential customers before spending.';
  return {
    overall,
    band: overallBand(overall.score),
    sources,
    coverage,
    framing: readinessFraming(overall.score),
    strongest,
    nextAction,
    groups: { market: groupScore(items, 'market'), execution: groupScore(items, 'execution') },
  };
}

export function itemsForGroup(report: StandardReport, group: CriterionGroup): ScorecardItem[] {
  const order = CRITERIA.filter((c) => c.group === group).map((c) => c.id);
  return order.map((id) => report.scorecard.find((s) => s.id === id)).filter((s): s is ScorecardItem => !!s);
}

/** Lowest-scoring criteria with a stated improvement: what needs strengthening. */
export function toStrengthen(report: StandardReport, max = 3): ScorecardItem[] {
  return [...report.scorecard]
    .filter((s) => s.score !== null && s.improvement)
    .sort((a, b) => (a.score ?? 0) - (b.score ?? 0))
    .slice(0, max);
}

/** Provenance for a chart: geography, period and whether the figures are actuals, forecasts or illustrative. */
export function chartProvenance(chart: Chart, sources: Source[], marketLabel: string): { geography: string; period: string; nature: string; sourceIndexes: number[] } {
  const idx = [...new Set(chart.series.map((s) => s.source_index).filter((n): n is number => typeof n === 'number'))];
  const cited = idx.map((i) => sources.find((s) => s.index === i)).filter((s): s is Source => !!s);
  if (chart.kind === 'evidence' && cited.length) {
    const geography = [...new Set(cited.map((s) => s.geography).filter(Boolean))].join(', ') || marketLabel;
    const period = [...new Set(cited.map((s) => s.period ?? s.published_date).filter(Boolean))].join(', ') || 'period not stated';
    const forecast = cited.some((s) => s.claim_type === 'forecast');
    const historical = cited.some((s) => s.claim_type === 'historical');
    const nature = forecast && historical ? 'Actuals and third-party forecast' : forecast ? 'Third-party forecast' : 'Reported figures';
    return { geography, period, nature, sourceIndexes: idx };
  }
  if (chart.kind === 'scenario') return { geography: marketLabel, period: 'illustrative, not a forecast', nature: 'Illustrative scenario computed from stated inputs and assumptions', sourceIndexes: [] };
  return { geography: marketLabel, period: '', nature: 'No suitable data', sourceIndexes: [] };
}

